// Generate simple ReachOS icons as data URIs in an HTML file
// For now, create minimal valid PNG files
const fs = require('fs');
const path = require('path');

// 1x1 green pixel PNG (valid PNG for development)
// In production, replace with real designed icons
const sizes = [16, 48, 128];
const iconDir = path.join(__dirname, '..', 'public', 'icons');

// Minimal valid PNG (1x1 pixel, green #00ba7c)
const createMinimalPNG = () => {
  // PNG signature + IHDR + IDAT + IEND for a 1x1 green pixel
  return Buffer.from([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
    0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, // 1x1
    0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xDE, // 8-bit RGB
    0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, 0x54, // IDAT chunk
    0x08, 0xD7, 0x63, 0x60, 0xF8, 0xCF, 0xC0, 0x00, 0x00, 0x00, 0x03, 0x00, 0x01,
    0x36, 0x28, 0x19, 0x00, // CRC
    0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, // IEND chunk
    0xAE, 0x42, 0x60, 0x82  // CRC
  ]);
};

if (!fs.existsSync(iconDir)) {
  fs.mkdirSync(iconDir, { recursive: true });
}

sizes.forEach(size => {
  const filePath = path.join(iconDir, `icon-${size}.png`);
  fs.writeFileSync(filePath, createMinimalPNG());
  console.log(`Created ${filePath}`);
});
